"use client";

import { useState } from "react";
import { AnimatePresence, motion } from "framer-motion";
import {
  ArrowUpRight,
  Ban,
  BadgeCheck,
  Bot,
  CheckCircle2,
  Eye,
  FileText,
  ShieldQuestion,
  Sparkles,
} from "lucide-react";
import { apiClient } from "@/lib/api-client";
import { toast } from "@/lib/hooks/use-toast";
import { useInvestigation } from "@/lib/hooks/useApi";
import type { CaseSummary } from "@/types";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from "@/components/ui/card";
import { SkeletonText } from "@/components/ui/skeleton";
import { cn } from "@/lib/utils";
import type { Investigation, RecommendedAction, Recommendation } from "@/types";

const ACTION_META: Record<
  RecommendedAction,
  { label: string; tone: "good" | "warning" | "serious" | "critical" | "info"; icon: React.ComponentType<{ className?: string }> }
> = {
  AUTO_APPROVE: { label: "Approve", tone: "good", icon: CheckCircle2 },
  MONITOR: { label: "Monitor", tone: "info", icon: Eye },
  REQUEST_VERIFICATION: { label: "Request verification", tone: "warning", icon: ShieldQuestion },
  ESCALATE: { label: "Escalate", tone: "serious", icon: ArrowUpRight },
  AUTO_BLOCK: { label: "Block", tone: "critical", icon: Ban },
};

function confidenceLabel(confidence: number | null | undefined): string {
  if (confidence === null || confidence === undefined) return "—";
  const pct = confidence <= 1 ? confidence * 100 : confidence;
  return `${Math.round(pct)}% confidence`;
}

/**
 * The one-button investigation. The agents draft; the analyst signs. Nothing
 * here closes a case on its own — the recommendation is advisory and every run
 * is persisted server-side for replay.
 */
export function AiInvestigationPanel({ caseId }: { caseId: string }) {
  const { data: investigation, mutate, isLoading } = useInvestigation(caseId);
  const [recommendation, setRecommendation] = useState<Recommendation | null>(null);
  const [summary, setSummary] = useState<CaseSummary | null>(null);
  const [running, setRunning] = useState(false);
  const [recommending, setRecommending] = useState(false);
  const [summarising, setSummarising] = useState(false);

  const loadSummary = async () => {
    setSummarising(true);
    try {
      setSummary(await apiClient.getCaseSummary(caseId));
    } catch (error) {
      toast.fromError(error, "Could not generate a case summary");
    } finally {
      setSummarising(false);
    }
  };

  const runInvestigation = async () => {
    setRunning(true);
    try {
      const result = await apiClient.runInvestigation(caseId);
      await mutate(result, { revalidate: false });
      toast.success("Investigation complete", "The agent wrote a narrative for this case.");
    } catch (error) {
      toast.fromError(error, "Investigation failed");
    } finally {
      setRunning(false);
    }
  };

  const runRecommendation = async () => {
    setRecommending(true);
    try {
      const result = await apiClient.runRecommendation(caseId);
      setRecommendation(result);
      toast.success("Recommendation ready", `Suggested action: ${ACTION_META[result.action]?.label ?? result.action}.`);
    } catch (error) {
      toast.fromError(error, "Could not generate a recommendation");
    } finally {
      setRecommending(false);
    }
  };

  return (
    <Card className="overflow-hidden">
      <CardHeader className="flex-row items-start justify-between gap-4 space-y-0 border-b border-line pb-4">
        <div className="flex items-start gap-3">
          <span className="relative grid size-9 shrink-0 place-items-center rounded-md bg-primary-wash">
            <Bot className="size-4 text-primary" />
            {running && (
              <span className="absolute inset-0 animate-pulse-ring rounded-md border-2 border-primary" />
            )}
          </span>
          <div className="space-y-1">
            <CardTitle>AI investigation</CardTitle>
            <CardDescription>
              {investigation
                ? `Generated by ${investigation.provider}. Advisory only — you sign the decision.`
                : "Reads the evidence, writes the narrative, recommends an action."}
            </CardDescription>
          </div>
        </div>
        <Button onClick={runInvestigation} loading={running} size="sm">
          {!running && <Sparkles />}
          {investigation ? "Re-run" : "Run investigation"}
        </Button>
      </CardHeader>

      <CardContent className="space-y-5">
        {isLoading ? (
          <SkeletonText lines={4} />
        ) : investigation ? (
          <InvestigationBody investigation={investigation} />
        ) : (
          <div className="flex flex-col items-start gap-2 rounded-md border border-dashed border-line-strong bg-surface-sunken px-4 py-5">
            <p className="text-sm font-medium text-ink">No investigation yet</p>
            <p className="max-w-lg text-xs leading-relaxed text-ink-secondary">
              Running an investigation gathers the transaction, device, velocity and
              geographic signals for this case, then writes an analyst-ready narrative
              with the indicators that drove it.
            </p>
          </div>
        )}

        {investigation && (
          <div className="border-t border-line pt-5">
            <div className="flex flex-wrap items-center justify-between gap-3">
              <div>
                <p className="text-sm font-medium text-ink">Recommended action</p>
                <p className="text-xs text-ink-muted">
                  A suggestion for the analyst, never an automatic decision.
                </p>
              </div>
              <div className="flex items-center gap-2">
                <Button variant="ghost" size="sm" onClick={loadSummary} loading={summarising}>
                  {!summarising && <FileText />}
                  {summary ? "Refresh summary" : "Case summary"}
                </Button>
                <Button variant="secondary" size="sm" onClick={runRecommendation} loading={recommending}>
                  {!recommending && <BadgeCheck />}
                  {recommendation ? "Re-run" : "Get recommendation"}
                </Button>
              </div>
            </div>

            {summary ? (
              <div className="mt-4 rounded-md border border-line bg-surface p-4">
                <p className="text-xs font-medium uppercase tracking-wide text-ink-muted">
                  Case summary for the audit record
                </p>
                <p className="mt-2 whitespace-pre-line text-sm leading-relaxed text-ink-secondary">
                  {summary.summary}
                </p>
              </div>
            ) : null}

            <AnimatePresence mode="wait">
              {recommendation && (
                <motion.div
                  key={recommendation.action}
                  initial={{ opacity: 0, y: 6 }}
                  animate={{ opacity: 1, y: 0 }}
                  exit={{ opacity: 0 }}
                  transition={{ duration: 0.22, ease: [0.16, 1, 0.3, 1] }}
                  className="mt-4 rounded-md border border-line bg-surface-sunken p-4"
                >
                  <div className="flex flex-wrap items-center gap-2">
                    <Badge
                      tone={ACTION_META[recommendation.action]?.tone ?? "info"}
                      icon={ACTION_META[recommendation.action]?.icon}
                    >
                      {ACTION_META[recommendation.action]?.label ?? recommendation.action}
                    </Badge>
                    <span className="text-xs text-ink-muted tabular">
                      {confidenceLabel(recommendation.confidence)}
                    </span>
                  </div>
                  <p className="mt-2.5 text-sm leading-relaxed text-ink-secondary">
                    {recommendation.reasoning}
                  </p>
                </motion.div>
              )}
            </AnimatePresence>
          </div>
        )}
      </CardContent>
    </Card>
  );
}

function InvestigationBody({ investigation }: { investigation: Investigation }) {
  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2">
        <Badge
          tone={investigation.likelyFraud ? "critical" : "good"}
          icon={investigation.likelyFraud ? Ban : CheckCircle2}
        >
          {investigation.likelyFraud ? "Likely fraud" : "Likely legitimate"}
        </Badge>
        <span className="text-xs text-ink-muted tabular">
          {confidenceLabel(investigation.confidence)}
        </span>
      </div>

      <p className="whitespace-pre-line text-sm leading-relaxed text-ink-secondary">
        {investigation.narrative}
      </p>

      {investigation.keyIndicators?.length ? (
        <div className="space-y-2">
          <p className="text-xs font-medium uppercase tracking-wide text-ink-muted">
            Key indicators
          </p>
          <ul className="space-y-1.5">
            {investigation.keyIndicators.map((indicator, index) => (
              <li key={index} className="flex items-start gap-2 text-sm text-ink-secondary">
                <span
                  className={cn(
                    "mt-1.5 size-1.5 shrink-0 rounded-full",
                    investigation.likelyFraud ? "bg-critical" : "bg-good"
                  )}
                  aria-hidden
                />
                {indicator}
              </li>
            ))}
          </ul>
        </div>
      ) : null}
    </div>
  );
}
